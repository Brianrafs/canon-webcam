def check_result(result: int, context: str = "") -> int:
    """Levanta EdsError quando a chamada EDSDK falhou; senão devolve o código."""
    if result != 0:
        msg = ERROR_MESSAGES.get(result, "Unknown error")
        raise EdsError(result, f"{context}: {msg}" if context else msg)
    return result